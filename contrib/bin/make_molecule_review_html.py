        parts.append('<button type="button" onclick="downloadCsv()">Download CSV</button>\n')
        parts.append('<button type="button" onclick="setAllVisible(true)">Check visible</button>\n')
        parts.append('<button type="button" onclick="setAllVisible(false)">Uncheck visible</button>\n')
