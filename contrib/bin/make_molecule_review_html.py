def main(argv: list[str]) -> int:
    args = parse_args(argv)

    if args.checkbox is not None and args.checkbox.strip() == "":
        raise ValueError("--checkbox must specify a non-empty column name")

    headers, rows = read_csv(args.input, args.max_rows)
    smiles_column = validate_smiles_column(headers, args.smiles_column)
    records = build_records(
        headers,
        rows,
        smiles_column,
        width=args.image_width,
        height=args.image_height,
        show_smiles_text=args.show_smiles_text,
    )
    page = build_html(
        title=args.title,
        headers=headers,
        smiles_column=smiles_column,
        records=records,
        checkbox_column=args.checkbox,
        checked_by_default=args.checked_by_default,
        source_name=args.input.name,
    )

    args.output.write_text(page, encoding="utf-8")
    print(f"Wrote {args.output} with {len(records)} molecules", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
